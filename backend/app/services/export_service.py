import io
import re
from typing import Optional
from reportlab.lib.pagesizes import A4
from reportlab.lib import colors
from reportlab.lib.styles import getSampleStyleSheet, ParagraphStyle
from reportlab.platypus import SimpleDocTemplate, Paragraph, Spacer, HRFlowable


class ExportService:
    @staticmethod
    def generate_markdown(topic: str, report_text: str, score: Optional[int] = None) -> str:
        header = f"# Research Dossier: {topic}\n"
        if score:
            header += f"*Quality Assessment: {score}/10 | Generated by Findly AI Research Engine*\n\n---\n\n"
        else:
            header += f"*Generated by Findly AI Research Engine*\n\n---\n\n"
        return header + report_text

    @staticmethod
    def generate_pdf(topic: str, report_text: str, score: Optional[int] = None) -> bytes:
        buffer = io.BytesIO()
        doc = SimpleDocTemplate(
            buffer,
            pagesize=A4,
            leftMargin=40,
            rightMargin=40,
            topMargin=40,
            bottomMargin=40,
        )

        styles = getSampleStyleSheet()

        # Custom distinct typography styles
        title_style = ParagraphStyle(
            "DocTitle",
            parent=styles["Title"],
            fontSize=22,
            leading=26,
            textColor=colors.HexColor("#0f172a"),
            alignment=0,
            spaceAfter=6,
        )
        meta_style = ParagraphStyle(
            "DocMeta",
            parent=styles["Normal"],
            fontSize=10,
            leading=14,
            textColor=colors.HexColor("#64748b"),
            spaceAfter=14,
        )
        h1_style = ParagraphStyle(
            "Heading1_Custom",
            parent=styles["Heading1"],
            fontSize=15,
            leading=19,
            textColor=colors.HexColor("#1e293b"),
            spaceBefore=12,
            spaceAfter=6,
            keepWithNext=True,
        )
        h2_style = ParagraphStyle(
            "Heading2_Custom",
            parent=styles["Heading2"],
            fontSize=12,
            leading=16,
            textColor=colors.HexColor("#334155"),
            spaceBefore=10,
            spaceAfter=4,
            keepWithNext=True,
        )
        body_style = ParagraphStyle(
            "Body_Custom",
            parent=styles["BodyText"],
            fontSize=10,
            leading=15,
            textColor=colors.HexColor("#1e293b"),
            spaceAfter=6,
        )
        bullet_style = ParagraphStyle(
            "Bullet_Custom",
            parent=styles["Normal"],
            fontSize=10,
            leading=15,
            textColor=colors.HexColor("#1e293b"),
            leftIndent=15,
            spaceAfter=4,
        )

        story = []

        # Header Title
        story.append(Paragraph(f"Research Dossier: {topic}", title_style))
        meta_text = f"Findly AI Research Engine"
        if score:
            meta_text += f" | Rigor Score: {score}/10"
        story.append(Paragraph(meta_text, meta_style))
        story.append(HRFlowable(width="100%", thickness=1, color=colors.HexColor("#cbd5e1"), spaceAfter=14))

        # Parse markdown lines
        lines = report_text.split("\n")
        for line in lines:
            line_str = line.strip()
            if not line_str:
                story.append(Spacer(1, 4))
                continue

            # Escaping XML entities for ReportLab
            clean_line = (
                line_str.replace("&", "&amp;")
                .replace("<", "&lt;")
                .replace(">", "&gt;")
            )

            # Convert markdown bold and italic formatting safely
            clean_line = re.sub(r"\*\*(.*?)\*\*", r"<b>\1</b>", clean_line)
            clean_line = re.sub(r"\*(.*?)\*", r"<i>\1</i>", clean_line)

            if line_str.startswith("# "):
                text = clean_line.lstrip("# ").strip()
                story.append(Paragraph(text, h1_style))
            elif line_str.startswith("## "):
                text = clean_line.lstrip("## ").strip()
                story.append(Paragraph(text, h1_style))
            elif line_str.startswith("### "):
                text = clean_line.lstrip("### ").strip()
                story.append(Paragraph(text, h2_style))
            elif line_str.startswith("- ") or line_str.startswith("* "):
                text = clean_line[2:].strip()
                story.append(Paragraph(f"• {text}", bullet_style))
            else:
                story.append(Paragraph(clean_line, body_style))

        doc.build(story)
        buffer.seek(0)
        return buffer.read()
